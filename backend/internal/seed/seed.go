// reasonCodes checks that the reference catalogue (migration 00011) is present and fills in the
// Telugu labels where none has been set.
func (r *runner) reasonCodes(ctx context.Context) error {
	var n int
	if err := r.tx.QueryRow(ctx, `SELECT count(*) FROM reason_codes WHERE is_active`).Scan(&n); err != nil {
		return err
	}
	if n == 0 {
		return errors.New("reason_codes is empty; run `rovo migrate up` first")
	}
	for _, l := range reasonLabelsTe {
		if err := r.exec(ctx, "reason_code_labels", `
			UPDATE reason_codes SET label_i18n = $3::jsonb WHERE category = $1 AND code = $2 AND label_i18n = '{}'::jsonb`,
			l.Category, l.Code, i18n(l.Te)); err != nil {
			return err
		}
	}
	return nil
}

