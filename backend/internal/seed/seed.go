// Package seed loads the Mahabubnagar demo dataset used by `rovo seed` (doc 10 §15.2): the city,
// its localities and fixture zone, an approved fee config (R18; no platform fee, R59), city
// app_config, platform ledger accounts, the bootstrap ADMIN_SUPER, four fictional restaurants
// with menus, four riders and two coupons.
//
// The seed is idempotent: row IDs are derived deterministically from natural keys (UUIDv5) and
// every insert is ON CONFLICT DO NOTHING, so a re-run adds what is missing and never overwrites
// edits made since. It runs in one transaction and is refused when ROVO_ENV=prod.
package seed

