// TOTPAAD is the additional authenticated data binding an admin's encrypted TOTP secret to its
// row; the identity module must use the same value to decrypt.
func TOTPAAD(userID uuid.UUID) []byte { return []byte("admin_credentials.totp:" + userID.String()) }

func (r *runner) admin(ctx context.Context) error {
	a := &r.res.Admin
	a.Email = AdminEmail
	cfg := r.opts.Config

	err := r.tx.QueryRow(ctx, `SELECT id FROM users WHERE kind = 'STAFF' AND email = $1 AND status <> 'ANONYMIZED'`, AdminEmail).Scan(&a.UserID)
	switch {
	case db.IsNoRows(err):
		a.UserID = ID("user", AdminEmail)
		a.Created = true
		if err := r.exec(ctx, "users", `
			INSERT INTO users (id, kind, email, email_verified_at, full_name, home_city_id)
			VALUES ($1,'STAFF',$2,$3,$4,$5)`, a.UserID, AdminEmail, r.opts.Now, AdminName, r.res.CityID); err != nil {
			return err
		}
	case err != nil:
		return err
	}
	// Global (city_id NULL) super-admin role.
	if err := r.exec(ctx, "user_roles", `
		INSERT INTO user_roles (id, user_id, role, granted_at) VALUES ($1,$2,'ADMIN_SUPER',$3) ON CONFLICT DO NOTHING`,
		ID("role", AdminEmail+"/ADMIN_SUPER"), a.UserID, r.opts.Now); err != nil {
		return err
	}

	var hasCreds bool
	var storedKeyID *string
	err = r.tx.QueryRow(ctx, `SELECT true, pii_key_id FROM admin_credentials WHERE user_id = $1`, a.UserID).Scan(&hasCreds, &storedKeyID)
	if err != nil && !db.IsNoRows(err) {
		return err
	}

	// Password: from the environment when given (also rotates an existing one), otherwise
	// generated once at creation and printed by the caller.
	password := cfg.AdminBootstrapPassword
	a.PasswordFromEnv = password != ""
	if !hasCreds && password == "" {
		password = auth.RandomToken(18)
		a.Password = password
	}
	if password != "" {
		hash, err := r.opts.Passwords.Hash(ctx, password)
		if err != nil {
			return err
		}
		// A generated password must be changed at first login; an operator-chosen one need not.
		if err := r.exec(ctx, "admin_credentials", `
			INSERT INTO admin_credentials (user_id, password_hash, must_change_password, password_changed_at)
			VALUES ($1,$2,$3,$4)
			ON CONFLICT (user_id) DO UPDATE SET password_hash = EXCLUDED.password_hash,
			  must_change_password = EXCLUDED.must_change_password, password_changed_at = EXCLUDED.password_changed_at,
			  failed_attempts = 0, locked_until = NULL`,
			a.UserID, hash, !a.PasswordFromEnv, r.opts.Now); err != nil {
			return err
		}
	}

	// TOTP is pre-enrolled only in dev/test, where the secret can be printed. Elsewhere the admin
	// enrols at first login. Re-enrol when the stored secret was sealed under a key this process
	// does not hold (e.g. an ephemeral dev key from a previous run).
	if cfg.DevLike() && (storedKeyID == nil || *storedKeyID != r.opts.Fields.ActiveKeyID()) {
		enrol, err := auth.NewTOTPSecret("rovo ("+string(cfg.Env)+")", AdminEmail)
		if err != nil {
			return err
		}
		sealed, keyID, err := r.opts.Fields.Encrypt([]byte(enrol.Secret), TOTPAAD(a.UserID))
		if err != nil {
			return err
		}
		if _, err := r.tx.Exec(ctx, `
			UPDATE admin_credentials SET totp_secret_enc = $2, pii_key_id = $3, totp_enrolled_at = $4, totp_last_step = NULL
			WHERE user_id = $1`, a.UserID, sealed, keyID, r.opts.Now); err != nil {
			return err
		}
		a.TOTPSecret, a.TOTPURI, a.TOTPEnrolledAtRun = enrol.Secret, enrol.URI, true
	}
	return nil
}

func (r *runner) feeConfig(ctx context.Context) error {
	slabs, err := json.Marshal(feeSlabs)
	if err != nil {
		return err
	}
	// APPROVED so the demo can quote immediately; a real city's fee config goes through
	// maker-checker (R31 family 3). platform_fee_paise is 0 per R59.
	return r.exec(ctx, "fee_configs", `
		INSERT INTO fee_configs (id, city_id, zone_id, version, effective_from, delivery_fee_slabs,
		  platform_fee_paise, small_cart_threshold_paise, small_cart_fee_paise, road_factor_milli,
		  max_serviceable_radius_m, cod_enabled, cod_max_order_paise, cod_first_order_max_paise,
		  rider_base_pay_paise, rider_base_distance_m, rider_per_km_paise, rider_cash_limit_paise,
		  eta_params, status, created_by)
		VALUES ($1,$2,NULL,1,$3,$4::jsonb,$5,$6,$7,$8,$9,true,$10,$11,$12,$13,$14,$15,$16::jsonb,'APPROVED',$17)
		ON CONFLICT DO NOTHING`,
		ID("fee_config", CityCode+"/v1"), r.res.CityID, effectiveFrom, string(slabs),
		int64(PlatformFeePaise), int64(SmallCartThresholdPaise), int64(SmallCartFeePaise), RoadFactorMilli,
		MaxServiceableRadiusM, int64(CODMaxOrderPaise), int64(CODFirstOrderMaxPaise),
		int64(RiderBasePayPaise), RiderBaseDistanceM, int64(RiderPerKmPaise), int64(RiderCashLimitPaise),
		etaParams, r.res.Admin.UserID)
}

